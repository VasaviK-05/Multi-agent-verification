"""Label classes for dataset records under the provisional automated labeling protocol.

VERIFIED_CORRECT is a benchmark gold answer confirmed by deterministic source checks.
SYNTHETIC_INCORRECT is generated by a recorded transformation and never human verified.
HUMAN_VERIFIED_INCORRECT requires a human review record; none exist in this repository.
UNRESOLVED candidates are kept separate and never enter binary metrics.
"""
from __future__ import annotations

VERIFIED_CORRECT = "VERIFIED_CORRECT"
SYNTHETIC_INCORRECT = "SYNTHETIC_INCORRECT"
HUMAN_VERIFIED_INCORRECT = "HUMAN_VERIFIED_INCORRECT"
UNRESOLVED = "UNRESOLVED"
LABEL_CLASSES = (VERIFIED_CORRECT, SYNTHETIC_INCORRECT, HUMAN_VERIFIED_INCORRECT, UNRESOLVED)
BINARY_LABEL = {VERIFIED_CORRECT: True, SYNTHETIC_INCORRECT: False, HUMAN_VERIFIED_INCORRECT: False, UNRESOLVED: None}
# Maps to app.game.offline.records.Example.label_method when a record becomes an Example.
EXAMPLE_LABEL_METHOD = {VERIFIED_CORRECT: "independent_ground_truth", SYNTHETIC_INCORRECT: "synthetic_transformation",
                        HUMAN_VERIFIED_INCORRECT: "independent_human"}
PROTOCOL = "provisional_automated_labeling_v1"


def label_fields(label_class: str, *, label_source: str, label_method: str, provenance: dict,
                 human_review_record: dict | None = None) -> dict:
    """Label-side fields shared by every labelled record."""
    if label_class not in LABEL_CLASSES:
        raise ValueError(f"Unknown label class: {label_class}")
    if label_class == HUMAN_VERIFIED_INCORRECT and not human_review_record:
        raise ValueError("HUMAN_VERIFIED_INCORRECT requires a human review record")
    if human_review_record and label_class != HUMAN_VERIFIED_INCORRECT:
        raise ValueError("Only HUMAN_VERIFIED_INCORRECT may carry a human review record")
    if not label_source.strip() or not label_method.strip():
        raise ValueError("Label source and method are required")
    return {"label_class": label_class, "answer_is_correct": BINARY_LABEL[label_class],
            "label_source": label_source, "label_method": label_method,
            "example_label_method": EXAMPLE_LABEL_METHOD.get(label_class),
            "label_protocol": PROTOCOL, "human_verified": label_class == HUMAN_VERIFIED_INCORRECT,
            "human_review_record": human_review_record, "label_provenance": provenance}


def research_v1_class(row: dict) -> str:
    """Class of an existing research_v1 candidate. Its negatives come from a controlled transformation."""
    status = row.get("correctness_status")
    if status == "verified_correct":
        return VERIFIED_CORRECT
    if status == "verified_incorrect":
        return HUMAN_VERIFIED_INCORRECT if row.get("human_review_record") else SYNTHETIC_INCORRECT
    return UNRESOLVED
